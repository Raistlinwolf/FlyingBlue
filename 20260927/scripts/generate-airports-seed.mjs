// Generates the airports seed migration from the OpenFlights-format airports list
// (Draft/airports.js in the repository root, the old prototype) and OpenFlights' country table.
//
//   node scripts/generate-airports-seed.mjs [path/to/airports.js]
//
// Output: supabase/migrations/20260927000400_seed_airports.sql
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(process.argv[2] ?? resolve(here, '../../Draft/airports.js'));
const countriesFile = resolve(here, 'data/openflights-countries.dat');
const output = resolve(here, '../supabase/migrations/20260927000400_seed_airports.sql');

const { airports } = await import(pathToFileURL(source).href);

// countries.dat rows: "Name","ISO","DAFIF"
const countryCodes = new Map();
for (const line of readFileSync(countriesFile, 'utf8').split(/\r?\n/)) {
  const match = line.match(/^"(.*)","([A-Z]{2})?",/);
  if (match && match[2]) countryCodes.set(match[1], match[2]);
}
// Names used in the airports list that countries.dat spells differently.
const aliases = {
  'Faroe Islands': 'FO', 'Congo (Brazzaville)': 'CG', 'Congo (Kinshasa)': 'CD', Swaziland: 'SZ',
  'Saint Helena': 'SH', 'Cape Verde': 'CV', 'Saint Pierre and Miquelon': 'PM', 'Wallis and Futuna': 'WF',
  'Midway Islands': 'UM', Micronesia: 'FM', 'Virgin Islands': 'VI', 'Saint Kitts and Nevis': 'KN',
  'Saint Lucia': 'LC', 'Saint Vincent and the Grenadines': 'VC', Kyrgyzstan: 'KG', Macau: 'MO',
  Burma: 'MM', Brunei: 'BN', 'East Timor': 'TL', 'Johnston Atoll': 'UM', 'Wake Island': 'UM',
};
for (const [name, code] of Object.entries(aliases)) countryCodes.set(name, code);

const sql = (value) => (value == null || value === '' ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

const seen = new Set();
const rows = [];
const unmatchedCountries = new Set();
for (const a of airports) {
  const iata = String(a.iata ?? '').trim().toUpperCase();
  if (!/^[A-Z]{3}$/.test(iata) || seen.has(iata)) continue;
  if (!Number.isFinite(a.lat) || !Number.isFinite(a.lon)) continue;
  seen.add(iata);
  const country = String(a.country ?? '').trim();
  const code = countryCodes.get(country) ?? null;
  if (!code && country) unmatchedCountries.add(country);
  rows.push(
    `(${sql(iata)}, ${sql(String(a.name ?? iata).trim())}, ${sql(String(a.city ?? '').trim())}, ${sql(code)}, ${a.lat}, ${a.lon})`,
  );
}

const chunks = [];
for (let i = 0; i < rows.length; i += 500) {
  chunks.push(
    'insert into public.airports (iata, name, city, country_code, latitude, longitude) values\n' +
      rows.slice(i, i + 500).join(',\n') +
      '\non conflict (iata) do update set name = excluded.name, city = excluded.city,' +
      ' country_code = excluded.country_code, latitude = excluded.latitude, longitude = excluded.longitude;',
  );
}

writeFileSync(
  output,
  `-- Generated by scripts/generate-airports-seed.mjs — do not edit by hand.\n` +
    `-- Source: OpenFlights airport database (ODbL), ${rows.length} airports with an IATA code.\n\n` +
    chunks.join('\n\n') +
    '\n',
);

console.log(`Wrote ${rows.length} airports to ${output}`);
if (unmatchedCountries.size) {
  console.log(`No ISO code for ${unmatchedCountries.size} country names:`, [...unmatchedCountries].join(', '));
}
